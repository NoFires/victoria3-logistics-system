"""Adapt building goods-flow artwork to the native CArrow vertex interface.

Only our own shader and definitions are distributed; textures stay in the game.
"""
import argparse
import json
from pathlib import Path
import shutil

STYLES = {
    'ironroadBuildingOutput': 'Output',
    'ironroadBuildingInput': 'Input',
    'ironroadBuildingYellow': 'Yellow',
    'ironroadGreen': 'Output',
    'ironroadRed': 'Input',
    'ironroadYellow': 'Yellow',
    'ironroadBlue': 'Blue',
    'ironroadTrafficGreen': 'TrafficGreen',
    'ironroadTrafficLime': 'TrafficLime',
    'ironroadTrafficYellow': 'TrafficYellow',
    'ironroadTrafficOrange': 'TrafficOrange',
    'ironroadTrafficRed': 'TrafficRed',
}
WIDTHS = (.5, .75, 1., 1.5, 2., 3., 4., 6.)
for _base, _effect in (('ironroadBuildingOutput', 'Output'), ('ironroadBuildingInput', 'Input'),
                       ('ironroadBuildingYellow', 'Yellow'), ('ironroadBlue', 'Blue'),
                       ('ironroadTan', 'Tan'), ('ironroadTrafficGreen', 'TrafficGreen'),
                       ('ironroadTrafficLime', 'TrafficLime'), ('ironroadTrafficYellow', 'TrafficYellow'),
                       ('ironroadTrafficOrange', 'TrafficOrange'), ('ironroadTrafficRed', 'TrafficRed')):
    for _band in range(len(WIDTHS)):
        STYLES[f'{_base}W{_band}'] = _effect
        if _base in ('ironroadBuildingOutput', 'ironroadBuildingInput') or _base.startswith('ironroadTraffic'):
            STYLES[f'{_base}BalancedW{_band}'] = _effect + 'Balanced'


def asset_text():
    definitions = []
    for name, effect in STYLES.items():
        width = WIDTHS[int(name[-1])] if name[-2:-1] == 'W' else 1.
        tan = effect == 'Tan'
        texture = 'gfx/map/movement_arrows/movearrow_move.dds' if tan else 'gfx/lines/arrow_diffuse.dds'
        overlay = 'gfx/map/movement_arrows/supply_arrow_color.dds' if tan else 'gfx/lines/line_mask.dds'
        shader = 'gfx/FX/arrow.shader' if tan else 'gfx/FX/ironroad_building_flow.shader'
        shader_effect = 'ArrowTextureColorEffect' if tan else f'IronroadBuilding{effect}'
        definitions.append(f'''arrowType = {{
    name = "{name}"
    texture = "{texture}"
    overlay = "{overlay}"
    effect = "{shader}"
    effectname = "{shader_effect}"
    size = {width:g}
    subdivisions = 5
    line_smoothing = yes
}}
''')
    return '\n'.join(definitions)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game-root', type=Path, required=True)
    ap.add_argument('--mod', type=Path, required=True)
    args = ap.parse_args()
    for texture in ('arrow_diffuse.dds', 'line_mask.dds'):
        path = args.game_root / 'game/gfx/lines' / texture
        if not path.is_file() or path.read_bytes()[:4] != b'DDS ':
            raise SystemExit(f'Missing building-flow texture: {path}')
    gfx = args.mod / 'gfx/models/military'
    fx = args.mod / 'gfx/FX'
    metadata = args.mod / '.metadata'
    for path in (gfx, fx, metadata):
        path.mkdir(parents=True, exist_ok=True)
    # Retire only files generated by earlier versions of these tools.
    for name in ('ironroad_preview.asset', 'ironroad_green.dds', 'ironroad_red.dds',
                 'ironroad_yellow.dds', 'ironroad_blue.dds'):
        (gfx / name).unlink(missing_ok=True)
    (gfx / 'ironroad_arrows.asset').write_text(asset_text(), encoding='utf-8')
    shutil.copyfile(Path(__file__).resolve().parents[1] / 'native/assets/building_flow.shader',
                    fx / 'ironroad_building_flow.shader')
    (metadata / 'metadata.json').write_text(json.dumps({
        'name': 'Ironroad Transport Arrow', 'id': 'ironroad_transport_arrow',
        'version': '0.2.0', 'supported_game_version': '1.13.*',
        'short_description': 'Native routes with building goods-flow arrows.',
        'tags': ['Graphics'], 'relationships': [],
        'game_custom_data': {'replace_paths': []},
    }, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(STYLES)} CArrow styles, building-flow shader and modern metadata.')


if __name__ == '__main__':
    main()
