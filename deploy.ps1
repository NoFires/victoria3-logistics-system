# DLL deployment: version.dll bootstrap + freight/freight.dll with embedded resources.
param(
  [string]$GameRoot = 'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3',
  [switch]$Uninstall,
  [switch]$InstallMod # Backward-compatible spelling; does not install a playset mod.
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $MyInvocation.MyCommand.Path
$bin = Join-Path $GameRoot 'binaries'
$dll = Join-Path $bin 'version.dll'
$backup = Join-Path $bin 'version.dll.ironroad-backup'
$distDll = Join-Path $repo 'dist\version.dll'
$runtime = Join-Path $bin 'freight'
$core = Join-Path $runtime 'freight.dll'
$distCore = Join-Path $repo 'dist\freight\freight.dll'
if (-not (Test-Path -LiteralPath $bin)) { throw "Game binaries folder not found: $bin" }
if (Get-Process victoria3 -ErrorAction SilentlyContinue) { throw 'Close Victoria 3 before deploying.' }

function Get-Sha($path) {
  if (Test-Path -LiteralPath $path) { (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash }
}
function Test-Ironroad($path) {
  if (-not (Test-Path -LiteralPath $path)) { return $false }
  return [bool](& findstr.exe /m /c:'Ironroad' "$path" 2>$null)
}

if ($Uninstall) {
  if ((Test-Path -LiteralPath $dll) -and (Test-Ironroad $dll)) {
    Remove-Item -LiteralPath $dll -Force
    Write-Host 'Removed Ironroad DLL.'
  }
  if ((Test-Path -LiteralPath $backup) -and -not (Test-Path -LiteralPath $dll)) {
    Move-Item -LiteralPath $backup -Destination $dll
    Write-Host 'Restored original version.dll.'
  }
  if ((Test-Path -LiteralPath $core) -and (Test-Ironroad $core)) {
    Remove-Item -LiteralPath $core -Force
    Write-Host 'Removed freight core DLL.'
  }
  Write-Host 'Preferences, logs and automatically generated caches were retained in binaries\freight.'
  exit 0
}

if (-not (Test-Path -LiteralPath $distCore)) { throw 'Build first: freight core DLL is missing.' }
if ((Test-Path -LiteralPath $core) -and -not (Test-Ironroad $core)) { throw 'A foreign freight.dll already exists; it was not overwritten.' }
if (-not (Test-Path -LiteralPath $distDll)) { throw 'Build first: powershell -File native\build.ps1' }
if ((Test-Path -LiteralPath $dll) -and (Get-Sha $dll) -ne (Get-Sha $distDll)) {
  if (-not (Test-Ironroad $dll)) {
    $existingBackup = Get-Sha $backup
    if (-not $existingBackup) { Copy-Item -LiteralPath $dll -Destination $backup }
    elseif ($existingBackup -ne (Get-Sha $dll)) { throw 'A foreign version.dll and a different backup both exist; neither was overwritten.' }
  }
}
New-Item -ItemType Directory -Force -Path $runtime | Out-Null
# Publish the payload before the bootstrap so a fresh installation is complete.
Copy-Item -LiteralPath $distCore -Destination ($core + '.tmp') -Force
Move-Item -LiteralPath ($core + '.tmp') -Destination $core -Force
Copy-Item -LiteralPath $distDll -Destination $dll -Force

# Retire only exact files generated by earlier Ironroad playset packages.
# Never recursively remove a user directory or modify the launcher database.
$userData = Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'Paradox Interactive\Victoria 3'
$legacy = Join-Path $userData 'mod\ironroad_arrow'
$ownedFiles = @('descriptor.mod', '.metadata\metadata.json',
  'gfx\models\military\ironroad_arrows.asset', 'gfx\models\military\ironroad_preview.asset',
  'gfx\models\military\ironroad_green.dds', 'gfx\models\military\ironroad_red.dds',
  'gfx\models\military\ironroad_yellow.dds', 'gfx\models\military\ironroad_blue.dds',
  'gfx\FX\ironroad_building_flow.shader')
foreach ($relative in $ownedFiles) {
  $path = Join-Path $legacy $relative
  if (Test-Path -LiteralPath $path -PathType Leaf) { Remove-Item -LiteralPath $path -Force }
}
$descriptor = Join-Path $userData 'mod\ironroad_arrow.mod'
if (Test-Path -LiteralPath $descriptor) { Remove-Item -LiteralPath $descriptor -Force }
$content = Join-Path $userData 'content_load.json'
if ((Test-Path -LiteralPath $content) -and (Get-Content -LiteralPath $content -Raw) -match 'ironroad_arrow') {
  & (Join-Path $repo 'tools\Update-ModLoad.ps1') -ContentFile $content -ModPath $legacy -Remove
}
Write-Host "Installed bootstrap -> $dll"
Write-Host "Installed freight core -> $core"
Write-Host 'No launcher mod, playset entry or external runtime data is required.'
Write-Host "Settings, logs and automatically managed caches: $runtime"
Write-Host 'Launch normally. The optional debug panel is closed by default; Insert toggles it.'
Write-Host 'Rollback: powershell -ExecutionPolicy Bypass -File deploy.ps1 -Uninstall'
